#!/usr/bin/env python
"""Stage 7B resume-fidelity experiment: continuous vs interrupted-and-resumed.

Runs a small deterministic budget (24 optimizer updates) two ways per scenario:

* **A** -- continuous 24 updates in one process;
* **B** -- 12 updates, save a full step-12 snapshot, exit, then resume that
  snapshot and continue to 24.

Two scenarios exercise the three Stage 7B fixes:

1. ``clean``   -- ``ipe % grad_accum == 0`` (192 micro-batches, 24 full windows).
2. ``partial`` -- ``ipe % grad_accum != 0`` (190 micro-batches; the 24th window
   is partial, size 6), which also makes the resume cross a partial window.

For each scenario the two runs must agree on the ENTIRE emitted data stream
(sample ids, augmented images, enc/pred masks), the optimizer-update and
micro-step counts, LR/WD at every update, the source-exposure ledger, and (up
to a declared numeric tolerance for CUDA nondeterminism) the final encoder,
predictor, target-encoder and optimizer state.

This is a test of the MACHINERY, not a result.  Output:
``reports/stage7b_resume_test_report.md`` and ``stage7b_resume_test.json``.

Usage::

    ./.venv-uv/bin/python -m tools.stage7b_resume_fidelity --dry-run
    ./.venv-uv/bin/python -m tools.stage7b_resume_fidelity --execute --device 1
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence

import yaml

from tools.stage7a_build_configs import BASE_CONFIG, ROOT
from tools.run_stage7a_pretraining import preflight

RUN_ROOT = Path('/data/agrisa_jepa_runs/stage7b_resume_fidelity')
MAX_STEPS = 24
INTERRUPT = 12
WARMUP = 2
SEED = 20261104
SCENARIOS = {
    # max_samples is chosen so batch_size=16 gives the stated ipe
    'clean': {'max_samples': 3072, 'ipe': 192, 'partial_windows': 0},
    'partial': {'max_samples': 3040, 'ipe': 190, 'partial_windows': 1},
}
#: numeric tolerance for weight / optimizer comparison (CUDA atomics under
#: BF16 are not guaranteed bitwise reproducible across processes).
WEIGHT_RTOL = 1e-3
WEIGHT_ATOL = 1e-5


def now_utc() -> str:
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def load_yaml(path: Path) -> Dict[str, object]:
    with path.open('r', encoding='utf-8') as handle:
        return yaml.safe_load(handle)


def build_configs(scenario: str) -> Dict[str, Dict[str, object]]:
    base = load_yaml(BASE_CONFIG)
    spec = SCENARIOS[scenario]
    root = RUN_ROOT / scenario

    def common(run_id: str, phase: str, arm: str) -> Dict[str, object]:
        cfg = copy.deepcopy(base)
        cfg['meta']['stage'] = 'stage7b_resume_fidelity'
        cfg['meta']['run_id'] = run_id
        cfg['meta']['phase'] = phase
        cfg['meta']['pair_id'] = f'fidelity_{scenario}'
        cfg['data']['seed'] = SEED
        cfg['data']['augmentation_seed'] = SEED
        cfg['data']['max_samples'] = spec['max_samples']
        cfg['optimization']['max_optimizer_steps'] = MAX_STEPS
        cfg['optimization']['warmup_steps'] = WARMUP
        cfg['optimization']['epochs'] = 5
        cfg['logging']['folder'] = str(root / arm)
        return cfg

    a = common(f'stage7b_fidelity_{scenario}_A', 'continuous', 'A')
    a['meta']['load_checkpoint'] = False
    a['meta']['read_checkpoint'] = None
    a['optimization']['interrupt_after_optimizer_steps'] = None
    a['optimization']['save_at_optimizer_steps'] = [MAX_STEPS]

    b1 = common(f'stage7b_fidelity_{scenario}_B', 'interrupted', 'B')
    b1['meta']['load_checkpoint'] = False
    b1['meta']['read_checkpoint'] = None
    b1['optimization']['interrupt_after_optimizer_steps'] = INTERRUPT
    b1['optimization']['save_at_optimizer_steps'] = [INTERRUPT]

    b2 = common(f'stage7b_fidelity_{scenario}_B', 'resumed', 'B')
    b2['meta']['load_checkpoint'] = True
    b2['meta']['read_checkpoint'] = f'jepa-step{INTERRUPT}.pth.tar'
    b2['optimization']['interrupt_after_optimizer_steps'] = None
    b2['optimization']['save_at_optimizer_steps'] = [MAX_STEPS]
    return {'A': a, 'B1': b1, 'B2': b2}


def write_configs(scenario: str, configs: Mapping[str, Mapping[str, object]]) -> Dict[str, Path]:
    paths: Dict[str, Path] = {}
    for key, cfg in configs.items():
        path = ROOT / 'configs' / f'stage7b_fidelity_{scenario}_{key}.yaml'
        path.write_text(
            '# Stage 7B resume-fidelity -- generated by tools/stage7b_resume_fidelity.py\n'
            '# NOT a result; validates continuous-vs-resumed equivalence.\n'
            + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True,
                             default_flow_style=False), encoding='utf-8')
        paths[key] = path
    return paths


def run(config_path: Path, device: int, cuda_index: int, trace: Path) -> int:
    env = dict(os.environ)
    env['CUDA_VISIBLE_DEVICES'] = str(device)
    env['AGRISA_TRACE_BATCHES'] = str(trace)
    command = [sys.executable, 'main.py', '--fname',
               str(config_path.relative_to(ROOT)), '--devices', f'cuda:{cuda_index}']
    print(f'--- fidelity run {config_path.name} on physical GPU{device} ---', flush=True)
    process = subprocess.run(command, cwd=ROOT, env=env, text=True)
    return process.returncode


def read_trace(path: Path) -> List[Dict[str, object]]:
    return [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line]


TRACE_EXACT_FIELDS = ('epoch', 'itr', 'micro_step', 'optimizer_step',
                      'window_size', 'imgs_sha', 'mask_enc_sha', 'mask_pred_sha',
                      'sample_ids')
TRACE_FLOAT_FIELDS = ('lr', 'wd')


def compare_traces(a: Sequence[Mapping[str, object]],
                   b: Sequence[Mapping[str, object]],
                   rtol: float = 1e-9) -> Dict[str, object]:
    """Diff two batch traces; returns counts + the first mismatches."""
    problems: List[str] = []
    if len(a) != len(b):
        problems.append(f'trace length differs: A={len(a)} B={len(b)}')
    exact_mismatch: Dict[str, int] = {f: 0 for f in TRACE_EXACT_FIELDS}
    float_mismatch: Dict[str, int] = {f: 0 for f in TRACE_FLOAT_FIELDS}
    first_mismatch: List[Dict[str, object]] = []
    for i, (ra, rb) in enumerate(zip(a, b)):
        row_problems = []
        for field in TRACE_EXACT_FIELDS:
            if ra.get(field) != rb.get(field):
                exact_mismatch[field] += 1
                row_problems.append(field)
        for field in TRACE_FLOAT_FIELDS:
            va, vb = float(ra.get(field, float('nan'))), float(rb.get(field, float('nan')))
            if abs(va - vb) > rtol * max(abs(va), abs(vb), 1e-12):
                float_mismatch[field] += 1
                row_problems.append(field)
        if row_problems and len(first_mismatch) < 10:
            first_mismatch.append({'index': i, 'fields': row_problems,
                                   'a': {k: ra.get(k) for k in row_problems},
                                   'b': {k: rb.get(k) for k in row_problems}})
    for field, count in exact_mismatch.items():
        if count:
            problems.append(f'{field}: {count} mismatching micro-batches')
    for field, count in float_mismatch.items():
        if count:
            problems.append(f'{field}: {count} mismatching micro-batches (rtol={rtol})')
    return {
        'ok': not problems,
        'problems': problems,
        'n_a': len(a), 'n_b': len(b),
        'exact_mismatch': exact_mismatch,
        'float_mismatch': float_mismatch,
        'first_mismatch': first_mismatch,
    }


def read_ledger(path: Path) -> List[Dict[str, str]]:
    import csv
    with path.open('r', encoding='utf-8', newline='') as handle:
        return list(csv.DictReader(handle))


def compare_ledgers(a: Sequence[Mapping[str, str]],
                    b: Sequence[Mapping[str, str]]) -> Dict[str, object]:
    """Comparable rows are (micro_step, sample_id) in emission order."""
    def rows(ledger):
        return [(int(r['micro_step']), r['sample_id'], r['physical_source_id'])
                for r in ledger]
    ra, rb = rows(a), rows(b)
    problems = []
    if len(ra) != len(rb):
        problems.append(f'ledger row count differs: A={len(ra)} B={len(rb)}')
    mismatch = 0
    for i, (x, y) in enumerate(zip(ra, rb)):
        if x != y:
            mismatch += 1
    if mismatch:
        problems.append(f'{mismatch} ledger rows differ')
    return {'ok': not problems, 'problems': problems,
            'n_a': len(ra), 'n_b': len(rb), 'row_mismatch': mismatch}


def _max_abs_diff(a, b):
    import torch
    if a.shape != b.shape:
        return float('inf'), True
    if not torch.is_floating_point(a):
        return (0.0, False) if torch.equal(a, b) else (float('inf'), True)
    diff = (a.float() - b.float()).abs()
    return float(diff.max()), False


def compare_state_dicts(a: Mapping[str, object], b: Mapping[str, object],
                        rtol: float = WEIGHT_RTOL,
                        atol: float = WEIGHT_ATOL) -> Dict[str, object]:
    import torch
    problems: List[str] = []
    if set(a) != set(b):
        problems.append('state_dict keys differ')
    worst = 0.0
    worst_key = None
    nonfinite = []
    for key in sorted(set(a) & set(b)):
        max_diff, shape_mismatch = _max_abs_diff(a[key], b[key])
        if shape_mismatch:
            nonfinite.append(key)
            continue
        if max_diff > worst:
            worst, worst_key = max_diff, key
    # scale-aware tolerance: allow rtol on the weight magnitude plus atol
    for key in sorted(set(a) & set(b)):
        ta, tb = a[key], b[key]
        if not torch.is_floating_point(ta):
            if not torch.equal(ta, tb):
                problems.append(f'{key}: integer tensor differs')
            continue
        scale = float(ta.float().abs().max()) if ta.numel() else 0.0
        tol = atol + rtol * scale
        max_diff, _ = _max_abs_diff(ta, tb)
        if max_diff > tol:
            problems.append(f'{key}: max|diff|={max_diff:.3e} > tol={tol:.3e}')
    return {'ok': not problems, 'problems': problems,
            'max_abs_diff': worst, 'worst_key': worst_key,
            'shape_mismatch_keys': nonfinite, 'rtol': rtol, 'atol': atol}


def compare_checkpoints(a: Mapping[str, object], b: Mapping[str, object]) -> Dict[str, object]:
    report: Dict[str, object] = {}
    problems: List[str] = []
    for name in ('encoder', 'predictor', 'target_encoder'):
        result = compare_state_dicts(a[name], b[name])
        report[name] = result
        problems.extend(f'{name}: {p}' for p in result['problems'])
    # optimizer state (exp_avg / exp_avg_sq per param)
    opt_problems = []
    sa, sb = a['opt']['state'], b['opt']['state']
    if set(sa) != set(sb):
        opt_problems.append('optimizer state param ids differ')
    for pid in sorted(set(sa) & set(sb)):
        for field in ('exp_avg', 'exp_avg_sq'):
            if field in sa[pid] and field in sb[pid]:
                max_diff, shape_mismatch = _max_abs_diff(sa[pid][field], sb[pid][field])
                if shape_mismatch:
                    opt_problems.append(f'param {pid} {field} shape mismatch')
                elif max_diff > WEIGHT_ATOL + WEIGHT_RTOL * float(
                        sa[pid][field].float().abs().max()):
                    opt_problems.append(
                        f'param {pid} {field}: max|diff|={max_diff:.3e}')
    report['optimizer'] = {'ok': not opt_problems, 'problems': opt_problems}
    problems.extend(f'optimizer: {p}' for p in opt_problems)
    # schedule position recorded at the final snapshot
    sched = {}
    for field in ('optimizer_steps', 'micro_steps',
                  'lr_at_snapshot', 'weight_decay_at_snapshot',
                  'ema_momentum_at_snapshot'):
        va, vb = a.get(field), b.get(field)
        same = (va == vb) if not isinstance(va, float) else abs(va - vb) <= 1e-12
        sched[field] = {'a': va, 'b': vb, 'equal': same}
        if not same:
            problems.append(f'{field}: A={va} B={vb}')
    report['schedule'] = sched
    report['ok'] = not problems
    report['problems'] = problems
    return report


def run_scenario(scenario: str, device: int, cuda_index: int) -> Dict[str, object]:
    import torch
    root = RUN_ROOT / scenario
    configs = build_configs(scenario)
    paths = write_configs(scenario, configs)
    started = now_utc()

    def checkpoint(arm: str, step: int) -> Path:
        return root / arm / f'jepa-step{step}.pth.tar'

    def require(cond, message):
        if not cond:
            raise RuntimeError(message)

    # A: continuous
    trace_a = root / 'trace_A.jsonl'
    trace_a.parent.mkdir(parents=True, exist_ok=True)
    if trace_a.exists():
        trace_a.unlink()
    require(run(paths['A'], device, cuda_index, trace_a) == 0, 'A failed')

    # B: interrupt at 12, then resume to 24 (same trace file, appended)
    trace_b = root / 'trace_B.jsonl'
    if trace_b.exists():
        trace_b.unlink()
    require(run(paths['B1'], device, cuda_index, trace_b) == 0, 'B part1 failed')
    # preserve part1 verification before part2 overwrites it
    (root / 'B' / 'training_verification.yaml').replace(
        root / 'B' / 'training_verification_part1.yaml')
    require(run(paths['B2'], device, cuda_index, trace_b) == 0, 'B part2 failed')

    trace_report = compare_traces(read_trace(trace_a), read_trace(trace_b))
    ledger_report = compare_ledgers(
        read_ledger(root / 'A' / 'source_exposure_ledger.csv'),
        read_ledger(root / 'B' / 'source_exposure_ledger.csv'))

    snap_a = torch.load(checkpoint('A', MAX_STEPS), map_location='cpu', weights_only=False)
    snap_b = torch.load(checkpoint('B', MAX_STEPS), map_location='cpu', weights_only=False)
    checkpoint_report = compare_checkpoints(snap_a, snap_b)

    with (root / 'A' / 'training_verification.yaml').open('r', encoding='utf-8') as h:
        ver_a = yaml.safe_load(h)
    with (root / 'B' / 'training_verification.yaml').open('r', encoding='utf-8') as h:
        ver_b = yaml.safe_load(h)
    counts = {
        'optimizer_steps_total': {'a': ver_a.get('optimizer_steps_total'),
                                  'b': ver_b.get('optimizer_steps_total')},
        'micro_steps_total': {'a': ver_a.get('micro_steps_total'),
                              'b': ver_b.get('micro_steps_total')},
        'partial_grad_accum_windows': {
            'a': ver_a.get('partial_grad_accum_windows'),
            'b': ver_b.get('partial_grad_accum_windows')},
        'partial_window_micro_steps': {
            'a': ver_a.get('partial_window_micro_steps'),
            'b': ver_b.get('partial_window_micro_steps')},
    }
    count_problems = [f'{k}: A={v["a"]} B={v["b"]}'
                      for k, v in counts.items() if v['a'] != v['b']]
    expected_partial = SCENARIOS[scenario]['partial_windows']
    if ver_a.get('partial_grad_accum_windows') != expected_partial:
        count_problems.append(
            f"partial windows A={ver_a.get('partial_grad_accum_windows')} "
            f"!= expected {expected_partial}")

    ok = (trace_report['ok'] and ledger_report['ok']
          and checkpoint_report['ok'] and not count_problems)
    return {
        'scenario': scenario,
        'ipe_expected': SCENARIOS[scenario]['ipe'],
        'started_at': started,
        'finished_at': now_utc(),
        'ok': ok,
        'trace': trace_report,
        'ledger': ledger_report,
        'checkpoint': checkpoint_report,
        'counts': counts,
        'count_problems': count_problems,
    }


def render_report(payload: Mapping[str, object]) -> str:
    lines = ['# Stage 7B — 恢复保真测试报告', '']
    lines.append(f'- 生成时间（UTC）：{payload["finished_at"]}')
    lines.append(f'- 预算：{MAX_STEPS} optimizer updates；中断/恢复点：{INTERRUPT}')
    lines.append(f'- 权重容差：rtol={WEIGHT_RTOL}, atol={WEIGHT_ATOL}（CUDA 非确定性）')
    lines.append('- 数据流 / mask / 计数 / LR / WD / ledger 要求逐 micro-batch 完全一致')
    lines.append('')
    lines.append('## 结论')
    lines.append('')
    lines.append(f'- 总体：**{"通过" if payload["ok"] else "失败"}**')
    lines.append('')
    for scenario, result in payload['scenarios'].items():
        lines.append(f'## 场景 `{scenario}`（ipe={result["ipe_expected"]}）')
        lines.append('')
        status = '通过' if result['ok'] else '**失败**'
        lines.append(f'- 状态：{status}')
        t = result['trace']
        lines.append(f'- 数据流 trace：A {t["n_a"]} / B {t["n_b"]} 条，'
                     f'{"一致" if t["ok"] else "不一致"}')
        l = result['ledger']
        lines.append(f'- ledger：A {l["n_a"]} / B {l["n_b"]} 行，'
                     f'{"一致" if l["ok"] else "不一致"}')
        c = result['checkpoint']
        lines.append('- 权重/优化器（容差内）：'
                     f'{"一致" if c["ok"] else "**超差**"}；'
                     f'最大 |diff|={c["max_abs_diff"]:.3e}'
                     f'（{c.get("worst_key")}）')
        for name in ('encoder', 'predictor', 'target_encoder'):
            st = c[name]
            lines.append(f'  - {name}：{"ok" if st["ok"] else "FAIL"}，'
                         f'max|diff|={st["max_abs_diff"]:.3e}')
        lines.append('- 计数：' + json.dumps(result['counts'], ensure_ascii=False))
        if result.get('count_problems'):
            for problem in result['count_problems']:
                lines.append(f'  - {problem}')
        for key in ('trace', 'ledger', 'checkpoint'):
            for problem in result[key]['problems']:
                lines.append(f'  - {key}: {problem}')
        lines.append('')
    return '\n'.join(lines) + '\n'


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--execute', action='store_true')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--device', type=int, default=1)
    parser.add_argument('--scenario', nargs='*', default=list(SCENARIOS))
    args = parser.parse_args(argv)

    if args.dry_run or not args.execute:
        print(json.dumps({
            'mode': 'dry-run', 'device': args.device,
            'scenarios': args.scenario,
            'max_steps': MAX_STEPS, 'interrupt': INTERRUPT, 'warmup': WARMUP,
            'configs': {s: {k: str((ROOT / 'configs' /
                                     f'stage7b_fidelity_{s}_{k}.yaml').relative_to(ROOT))
                            for k in ('A', 'B1', 'B2')} for s in args.scenario},
        }, indent=2, ensure_ascii=False))
        return 0

    guard = preflight(args.device, 30000, 5, False)
    print(json.dumps(guard, indent=2, ensure_ascii=False))
    if guard['problems']:
        print('REFUSING: fidelity test needs a clean, free GPU1', file=sys.stderr)
        return 1

    results = {}
    for scenario in args.scenario:
        print(f'=== fidelity scenario {scenario} ===', flush=True)
        results[scenario] = run_scenario(scenario, args.device, 0)

    payload = {
        'schema_version': 'stage7b_resume_fidelity/v1',
        'generated_at': now_utc(),
        'max_steps': MAX_STEPS, 'interrupt': INTERRUPT,
        'weight_rtol': WEIGHT_RTOL, 'weight_atol': WEIGHT_ATOL,
        'scenarios': results,
        'ok': all(r['ok'] for r in results.values()),
    }
    reports = ROOT / 'reports'
    reports.mkdir(exist_ok=True)
    (reports / 'stage7b_resume_test.json').write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    (reports / 'stage7b_resume_test_report.md').write_text(
        render_report(payload), encoding='utf-8')
    print(json.dumps({'ok': payload['ok'],
                      'scenarios': {k: v['ok'] for k, v in results.items()}},
                     indent=2))
    return 0 if payload['ok'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
