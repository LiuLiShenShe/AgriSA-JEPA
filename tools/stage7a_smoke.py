#!/usr/bin/env python
"""Small-scale Stage 7A smoke: interrupt / snapshot / resume / continue.

This is NOT a result.  It validates the machinery the 20k/50k run depends on,
before any long GPU budget is spent:

1. a mid-epoch ``interrupt_after_optimizer_steps`` saves a full state and exits
   WITHOUT changing the schedule horizon (``max_optimizer_steps`` is the one and
   only horizon);
2. ``save_at_optimizer_steps`` writes both the full ``jepa-step<N>.pth.tar`` and
   the encoder-only ``jepa-encoder-step<N>.pth``;
3. resuming the full step-N checkpoint continues the SAME schedule: optimizer
   steps do not reset, LR / WD / EMA land exactly on the schedule position, and
   the final count equals the horizon.

The smoke uses a 24-update horizon (12 + resume to 24) so it runs in minutes on
real images.  The 50,000-update horizon arithmetic is verified analytically by
``tools/check_stage7a_protocol.py`` and ``tests/test_stage7a_checkpoint_curve.py``;
this smoke exercises the identical train.py code path end to end.

Usage::

    ./.venv-uv/bin/python -m tools.stage7a_smoke --device 1 --execute
    ./.venv-uv/bin/python -m tools.stage7a_smoke --device 1
"""

from __future__ import annotations

import argparse
import copy
import json
import math
import os
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence

import yaml

from tools.stage7a_build_configs import BASE_CONFIG, ROOT, sha256_file
from tools.run_stage7a_pretraining import (
    expected_ema,
    expected_lr,
    expected_wd,
    preflight,
)

SMOKE_ROOT = '/data/agrisa_jepa_runs/stage7a_smoke'
SMOKE_MAX_STEPS = 24
SMOKE_INTERRUPT = 12
SMOKE_SAVE_AT = [6, 12, 24]
SMOKE_WARMUP = 2


def now_utc() -> str:
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def load(path: Path) -> Dict[str, object]:
    with path.open('r', encoding='utf-8') as handle:
        return yaml.safe_load(handle)


def build_smoke_configs() -> Dict[str, object]:
    base = load(BASE_CONFIG)
    part1 = copy.deepcopy(base)
    part1['meta']['stage'] = 'stage7a_smoke'
    part1['meta']['run_id'] = 'stage7a_smoke'
    part1['meta']['phase'] = 'smoke_part1_interrupt'
    part1['data']['seed'] = 20261029
    part1['data']['augmentation_seed'] = 20261029
    part1['optimization']['max_optimizer_steps'] = SMOKE_MAX_STEPS
    part1['optimization']['interrupt_after_optimizer_steps'] = SMOKE_INTERRUPT
    part1['optimization']['save_at_optimizer_steps'] = list(SMOKE_SAVE_AT)
    part1['optimization']['warmup_steps'] = SMOKE_WARMUP
    part1['optimization']['epochs'] = 24
    part1['logging']['folder'] = SMOKE_ROOT

    part2 = copy.deepcopy(part1)
    part2['meta']['phase'] = 'smoke_part2_resume'
    part2['meta']['load_checkpoint'] = True
    part2['meta']['read_checkpoint'] = f'jepa-step{SMOKE_INTERRUPT}.pth.tar'
    part2['optimization']['interrupt_after_optimizer_steps'] = None
    part2['optimization']['save_at_optimizer_steps'] = [SMOKE_MAX_STEPS]
    return {'part1': part1, 'part2': part2}


def write_configs(configs: Mapping[str, object]) -> Dict[str, Path]:
    paths: Dict[str, Path] = {}
    for key in ('part1', 'part2'):
        path = ROOT / 'configs' / f'stage7a_smoke_{key}.yaml'
        path.write_text(
            '# Stage 7A smoke -- generated by tools/stage7a_smoke.py\n'
            '# NOT a result; validates interrupt/snapshot/resume machinery.\n'
            + yaml.safe_dump(configs[key], sort_keys=False, allow_unicode=True,
                             default_flow_style=False), encoding='utf-8')
        paths[key] = path
    return paths


def run(config_path: Path, device: int, phase: str) -> int:
    run_dir = Path(SMOKE_ROOT)
    run_dir.mkdir(parents=True, exist_ok=True)
    console = run_dir / f'console_{phase}.log'
    env = dict(os.environ)
    env['CUDA_VISIBLE_DEVICES'] = str(device)
    command = [sys.executable, 'main.py', '--fname', str(config_path.relative_to(ROOT)),
               '--devices', f'cuda:{device}']
    print(f'--- smoke {phase} on physical GPU{device} ---', flush=True)
    started = time.time()
    with console.open('w', encoding='utf-8') as handle:
        process = subprocess.run(command, cwd=ROOT, env=env,
                                 stdout=handle, stderr=subprocess.STDOUT, text=True)
    return process.returncode if process.returncode == 0 else 1


def verify_schedule(run_dir: Path, step: int, cfg: Mapping[str, object]) -> List[str]:
    import torch
    problems: List[str] = []
    full = run_dir / f'jepa-step{step}.pth.tar'
    if not full.is_file():
        return [f'missing {full.name}']
    snap = torch.load(full, map_location='cpu', weights_only=False)
    if int(snap.get('optimizer_steps', -1)) != step:
        problems.append(f'{full.name}: optimizer_steps {snap.get("optimizer_steps")} != {step}')
    if not math.isclose(float(snap.get('lr_at_snapshot', 0)), expected_lr(step, cfg),
                        rel_tol=1e-6, abs_tol=1e-12):
        problems.append(f'{full.name}: LR not on schedule')
    if not math.isclose(float(snap.get('weight_decay_at_snapshot', 0)),
                        expected_wd(step, cfg), rel_tol=1e-6, abs_tol=1e-12):
        problems.append(f'{full.name}: WD not on schedule')
    if not math.isclose(float(snap.get('ema_momentum_at_snapshot', 0)),
                        expected_ema(step, cfg), rel_tol=1e-6, abs_tol=1e-12):
        problems.append(f'{full.name}: EMA not on schedule')
    return problems


def verify(resume_sha: Optional[str], part1_verification: Path) -> Dict[str, object]:
    run_dir = Path(SMOKE_ROOT)
    cfg = build_smoke_configs()['part1']
    problems: List[str] = []
    v1 = load(part1_verification)
    if v1.get('optimizer_steps_total') != SMOKE_INTERRUPT:
        problems.append(f'part1 steps {v1.get("optimizer_steps_total")} != {SMOKE_INTERRUPT}')
    if v1.get('max_optimizer_steps') != SMOKE_MAX_STEPS:
        problems.append('part1 horizon != 24')
    if v1.get('loss_finite') is not True:
        problems.append('part1 loss not finite')
    for step in (SMOKE_SAVE_AT[0], SMOKE_SAVE_AT[1]):
        if not (run_dir / f'jepa-step{step}.pth.tar').is_file():
            problems.append(f'missing full snapshot at {step}')
        if not (run_dir / f'jepa-encoder-step{step}.pth').is_file():
            problems.append(f'missing encoder snapshot at {step}')
        problems.extend(verify_schedule(run_dir, step, cfg))
    # continuity: part1 step12 sits on the 24-update schedule
    problems.extend(verify_schedule(run_dir, SMOKE_INTERRUPT, cfg))
    snap12_sha = sha256_file(run_dir / f'jepa-step{SMOKE_INTERRUPT}.pth.tar')

    if resume_sha and snap12_sha != resume_sha:
        problems.append('step12 snapshot SHA changed across phases')

    v2 = load(run_dir / 'training_verification.yaml')
    if v2.get('optimizer_steps_total') != SMOKE_MAX_STEPS:
        problems.append(f'part2 steps {v2.get("optimizer_steps_total")} != {SMOKE_MAX_STEPS}')
    if not (run_dir / f'jepa-step{SMOKE_MAX_STEPS}.pth.tar').is_file():
        problems.append('missing final snapshot at 24')
    problems.extend(verify_schedule(run_dir, SMOKE_MAX_STEPS, cfg))
    # the resumed model must have moved beyond the step-12 snapshot
    import torch
    final_snap = torch.load(run_dir / f'jepa-step{SMOKE_MAX_STEPS}.pth.tar',
                            map_location='cpu', weights_only=False)
    mid_snap = torch.load(run_dir / f'jepa-step{SMOKE_INTERRUPT}.pth.tar',
                          map_location='cpu', weights_only=False)
    key = 'module.blocks.0.mlp.fc1.weight'
    if key in final_snap['encoder'] and key in mid_snap['encoder']:
        if torch.equal(final_snap['encoder'][key], mid_snap['encoder'][key]):
            problems.append('resumed encoder did not move past the step-12 snapshot')
    return {
        'ok': not problems,
        'problems': problems,
        'part1_steps': SMOKE_INTERRUPT,
        'part2_steps': SMOKE_MAX_STEPS,
        'lr_at_interrupt': expected_lr(SMOKE_INTERRUPT, cfg),
        'lr_at_final': expected_lr(SMOKE_MAX_STEPS, cfg),
        'step12_sha': snap12_sha,
    }


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--device', type=int, default=1)
    parser.add_argument('--execute', action='store_true')
    args = parser.parse_args(argv)

    guard = preflight(args.device, 30000, 5, False)
    print(json.dumps(guard, indent=2, ensure_ascii=False))
    if guard['problems']:
        print('REFUSING: smoke needs a clean, free GPU1', file=sys.stderr)
        for problem in guard['problems']:
            print(f'  - {problem}', file=sys.stderr)
        return 1

    configs = build_smoke_configs()
    paths = write_configs(configs)
    if not args.execute:
        print(json.dumps({'mode': 'dry-run', 'device': args.device,
                          'configs': {k: str(v.relative_to(ROOT)) for k, v in paths.items()},
                          'max_steps': SMOKE_MAX_STEPS,
                          'interrupt': SMOKE_INTERRUPT,
                          'save_at': SMOKE_SAVE_AT,
                          'warmup_steps': SMOKE_WARMUP}, indent=2, ensure_ascii=False))
        return 0

    run_dir = Path(SMOKE_ROOT)
    if run_dir.exists() and any(p.name != 'console_part1.log'
                                for p in run_dir.iterdir()):
        print(f'REFUSING: smoke dir not empty: {run_dir}', file=sys.stderr)
        return 1
    if run(paths['part1'], args.device, 'part1') != 0:
        print('smoke part1 failed', file=sys.stderr)
        return 1
    run_dir.mkdir(parents=True, exist_ok=True)
    part1_verification = run_dir / 'training_verification_part1.yaml'
    (run_dir / 'training_verification.yaml').replace(part1_verification)
    snap12_sha = sha256_file(run_dir / f'jepa-step{SMOKE_INTERRUPT}.pth.tar')
    if run(paths['part2'], args.device, 'part2') != 0:
        print('smoke part2 failed', file=sys.stderr)
        return 1
    report = verify(snap12_sha, part1_verification)
    (run_dir / 'smoke_report.json').write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0 if report['ok'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
