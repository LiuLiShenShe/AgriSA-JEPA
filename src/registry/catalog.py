def all_sources() -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    rows.extend(agrifield_sources())
    seen = {r['source_id'] for r in rows}
    for row in agrifm_sources():
        # Agri-FM refs that are the same physical dataset as an AgriField row are
        # kept separate (different retained counts / different access path) but
        # their overlap is recorded rather than silently merged.
        rows.append(row)
        seen.add(row['source_id'])
    rows.extend(downstream_sources())
    return rows
