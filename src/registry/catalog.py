"""Curated Stage 5A agricultural source catalog.

Every row here is traceable to a primary document:

* ``agrifield40k`` -- the pinned AgriField-40K dataset card
  (``dtu-pcas/AgriField-40K@7f530c6``) and Tzouras et al. 2026 (arXiv:2608.07984).
* ``agrifmplus``  -- Al Nahian et al., CVPRW 2025, Table 1 + reference list.
* ``project_v1``  -- sources actually used by ``agrifield40k-v1``.
* ``downstream``  -- datasets reserved for evaluation, never for pretraining.

Counts are deliberately split: ``images_reported`` is what the *paper* says,
``files_remote`` is what the remote archive lists, ``files_downloaded`` is what
is on this machine, ``images_decoded`` passed a decode audit, and
``images_approved`` passed every gate.  A row never derives one from another.

Nothing in this module downloads or trusts data; it only records what has been
checked.  ``state`` is downgraded to ``DISCOVERED``/``URL_VERIFIED`` whenever the
supporting evidence is missing.
"""

