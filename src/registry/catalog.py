def _fm(ref: str, name: str, count: int, year: str, url: str,
        license_: str = 'unverified', category: str = '',
        domain: str = 'crop;field', platform: str = 'handheld camera',
        modality: str = 'RGB', notes: str = '',
        paper_url: str = FM_PAPER) -> Dict[str, object]:
    state = 'URL_VERIFIED' if url.startswith('http') else 'DISCOVERED'
    if license_ not in ('unverified', '') and url.startswith('http'):
        state = 'LICENSE_VERIFIED'
    return _row(
        source_id=f'agrifm_ref{ref}',
        official_name=name,
        catalog_groups='agrifmplus',
        paper=f'{FM_PAPER_CITE} ref [{int(ref)}]',
        year=year, paper_url=paper_url, download_url=url,
        category=category or 'pretraining imagery', domain=domain,
        platform=platform, modality=modality, images_reported=count,
        license=license_,
        license_evidence=(f'Agri-FM+ Table 1 / reference list (ref [{int(ref)}])'
                          if license_ != 'unverified' else ''),
        attribution_required='yes' if license_ != 'unverified' else '',
        allowed_in_project='pending' if license_ == 'unverified' else 'yes',
        state=state,
        evidence=f'Agri-FM+ Table 1 ref [{int(ref)}], {count} images; '
                 f'URL taken verbatim from reference list',
        notes=notes)


